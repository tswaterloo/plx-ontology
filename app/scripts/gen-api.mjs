#!/usr/bin/env node
// Regenerates src/lib/openapi.d.ts from operator_api/openapi.json (the contract).
// `node scripts/gen-api.mjs --check` exits 1 when the committed file is stale.
import openapiTS, { astToString } from "openapi-typescript";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const spec = fileURLToPath(new URL("../../operator_api/openapi.json", import.meta.url));
const out = fileURLToPath(new URL("../src/lib/openapi.d.ts", import.meta.url));

export async function generate() {
  const ast = await openapiTS(JSON.parse(readFileSync(spec, "utf8")), { exportType: true });
  return "// GENERATED by scripts/gen-api.mjs from operator_api/openapi.json. Do not edit.\n" + astToString(ast);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    const same = existsSync(out) && readFileSync(out, "utf8") === text;
    if (!same) {
      console.error("src/lib/openapi.d.ts is stale: run npm run gen:api");
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${out}`);
  }
}
