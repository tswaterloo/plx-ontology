"""SharePoint list items as mention documents (``ontology.mentions.Document`` of kind
``sharepoint_list_item``), so identifiers typed into list fields link as file text does.

``ontology.project.SharePointCaptures.document_groups`` yields one group per retained
list-item version of the list capture (``ontology.project_graph.SharePointListCaptures``),
keyed by the document code, this module's bytes and the version's handle, digest and
interval. The mention links are generated by ``ontology.schema``
``SHAREPOINT_LIST_MENTION_LINK_RULE`` (``SharePointListItem.mentions_<type>``, leads).

Stdlib only.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Iterator, Mapping
from urllib.parse import unquote

KIND = "sharepoint_list_item"


def code() -> str:
    """Digest of this module (a list item document group's key holds it)."""
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def document_rows(lists: Any) -> Iterator[dict[str, Any]]:
    """Every retained list-item version of ``lists`` (a ``SharePointListCaptures``) as the
    plain row its document is read from: handle, digest, interval and the captured item."""
    from integrations.capture_store import make_handle

    for row in lists._conn.execute(
            "SELECT capture_id, path, digest, payload, recorded_at, superseded_at FROM "
            "versions WHERE kind = ? ORDER BY unit, path, recorded_at, capture_id",
            (lists.kind.name,)):
        path = lists.kind.canonical_path([unquote(p) for p in str(row["path"]).split("/")])
        yield {"handle": make_handle(lists.kind, path, lists.generation, row["capture_id"]),
               "digest": row["digest"], "recorded_at": row["recorded_at"],
               "superseded_at": row["superseded_at"],
               "row": json.loads(row["payload"]).get("row") or {}}


def list_item_document(item: Mapping[str, Any]) -> Any:
    """A list item version as a mention document: each text value of its ``fields`` (a
    list column: a PO number, a vendor, an order typed into a tracker), cited
    ``row.fields.<column>`` under the version's own handle. Columns SharePoint keeps for
    itself (``@odata``, ``_`` names) and empty values are skipped; None when nothing is
    left. Who typed a value is unknown: ``unknown`` (external assertions, leads)."""
    from ontology.mentions import Document, TextField

    record = item.get("row") or {}
    values = record.get("fields") if isinstance(record.get("fields"), Mapping) else {}
    handle = item["handle"]
    fields = tuple(TextField(handle, f"row.fields.{name}", value)
                   for name, value in sorted(values.items())
                   if isinstance(name, str) and not name.startswith(("@", "_"))
                   and isinstance(value, str) and value.strip())
    if not fields:
        return None
    return Document(handle, KIND, fields, sender_class="unknown", digest=item["digest"],
                    recorded_at=item["recorded_at"], superseded_at=item["superseded_at"],
                    date=record.get("lastModifiedDateTime") or record.get("createdDateTime"))


__all__ = ["KIND", "code", "document_rows", "list_item_document"]
